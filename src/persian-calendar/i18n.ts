export const BASE_PATH = 'persian-calendar';

const faDigits = new Intl.NumberFormat('fa-IR', { useGrouping: false });
const faNumber = new Intl.NumberFormat('fa-IR');
const enNumber = new Intl.NumberFormat('en-US');

/** Format a number for the given language (Persian digits on the Persian pages) */
export const formatNumber = (n: number, lang: Lang, grouping = true) =>
  lang === 'fa' ? (grouping ? faNumber : faDigits).format(n) : grouping ? enNumber.format(n) : String(n);

export const formatDate = (date: Date, lang: Lang) =>
  new Intl.DateTimeFormat(lang === 'fa' ? 'fa-IR' : 'en-US', { dateStyle: 'long', timeZone: 'Asia/Tehran' }).format(date);

